def parse_shared_slots(spec, pages, table):
    """{page name: [(slot index, gen_ui Control)]} for "gb.sharedSlots"."""
    out = {}
    for name, items in spec["gb"]["sharedSlots"].items():
        page = next((pg for pg in pages if pg.name == name), None)
        if page is None:
            raise BuildError('"gb.sharedSlots" names page "%s", which is not in "mpc.pages"' % name)
        for k, item in enumerate(items):
            where = "gb.sharedSlots.%s[%d]" % (name, k)
            ctl = gen_ui.parse_control(item["control"], table, where)
            i = item["row"] * 4 + item["col"]
            occ = page.controls[i] if i < len(page.controls) else None
            if ctl.param is None or occ is None or occ.param is None:
                raise BuildError("%s: a shared slot needs a bound control over a bound control" % where)
            if not (ctl.visible and occ.visible and ctl.visible[0] is occ.visible[0] and ctl.visible[1] != occ.visible[1]):
                raise BuildError('%s: "%s" and "%s" must have visibleWhen on the same parameter with different choices'
                                 % (where, ctl.param.name, occ.param.name))
            out.setdefault(name, []).append((i, ctl))
    return out


def resolve_dynamics(spec, pages, table):
    """{page name: [dict]} with bounds (tab coordinates), param, image/frames or label style."""
    gb = spec["gb"]
    pal = gb["palette"]
    out = {}
    for name, items in gb["dynamics"].items():
        page = next((pg for pg in pages if pg.name == name), None)
        if page is None:
            raise BuildError('"gb.dynamics" names page "%s", which is not in "mpc.pages"' % name)
        res = []
        for k, d in enumerate(items):
            where = "gb.dynamics.%s[%d]" % (name, k)
            p = table.lookup(d["param"], where)
            r = dict(d)
            r["paramObj"] = p
            if d["kind"] == "filmStrip":
                if d["art"] not in ui_art.STRIP_ART:
                    raise BuildError("%s: unknown film-strip art %r" % (where, d["art"]))
                aw, ah, n = ui_art.STRIP_ART[d["art"]]
                steps = len(p.choices) if p.is_discrete else None
                if steps != n:
                    raise BuildError('%s: "%s" has %s steps but the %s strip has %d frames'
                                     % (where, p.name, steps, d["art"], n))
                colour = d.get("colour")
                if ("%s" in STRIP_FILES[d["art"]]) != (colour is not None):
                    raise BuildError("%s: %s strips %s a colour" % (where, d["art"], "need" if colour is None else "take no"))
                if colour is not None and colour not in gb["colours"]:
                    raise BuildError("%s: unknown colour %r" % (where, colour))
                r["image"] = strip_file(d["art"], colour)
                r["frames"] = n
                r["bounds"] = (gen_ui.SLOT_X[d["col"]] + d["x"], gen_ui.SLOT_Y[d["row"]] + d["y"], aw * 2, ah * 2)
                default = p.default or 0.0
                r["defaultFrame"] = int(round(default * (n - 1)))
            elif d["kind"] == "valueLabel":
                if d.get("colour") not in pal:
                    raise BuildError("%s: label colour must name a gb.palette role" % where)
                r["argb"] = "ff" + pal[d["colour"]].lower()
                if "column" in d:
                    grids = [p2 for p2 in gb["panels"].get(name, []) if p2["kind"] == "lcdTable"]
                    if len(grids) != 1:
                        raise BuildError('%s: "column" needs the page\'s lcdTable panel' % where)
                    r["bounds"] = table_column_label_bounds(panel_bounds(grids[0]), grids[0]["grid"], d["column"])
                    r["inTable"] = True
                else:
                    r["bounds"] = (gen_ui.SLOT_X[d["col"]] + d["x"], gen_ui.SLOT_Y[d["row"]] + d["y"], d["w"], d["h"])
            else:
                raise BuildError("%s: unknown dynamic kind %r" % (where, d["kind"]))
            x, y, w, h = r["bounds"]
            if x < 0 or y < 0 or x + w > TAB_W or y + h > TAB_H:
                raise BuildError("%s: bounds %r leave the tab" % (where, r["bounds"]))
            res.append(r)
        out[name] = res
    return out


def dynamic_entry(d):
    p = d["paramObj"]
    if d["kind"] == "filmStrip":
        data = gen_ui.obj(("version", 2), ("imageType", "FilmStrip"), ("colour", "0"), ("image", d["image"]),
                          ("numFrames", d["frames"]), ("handleName", "Data"))
        return gen_ui.entry("dyn %s" % p.name, "Image", data, rect_str(d["bounds"]), "No", "Hide", "Always",
                            remap=[("Data", p.handle)])
    data = gen_ui.label_data("Value", d["argb"], d["fontHeight"], "left verticallyCentred")
    return gen_ui.entry("dyn %s" % p.name, "Label", data, rect_str(d["bounds"]), "No", "Hide", "Always",
                        remap=[("Data", p.handle)])


def qlink_rows(direction, margin):
    """qlinkBoundsData for a row bank layout: one rectangle per screen row, in bank order."""
    mx, my = margin
    x = gen_ui.SLOT_X[0] - mx
    w = gen_ui.SLOT_X[3] + gen_ui.SLOT_W + mx - x
    rects = ["%d %d %d %d" % (x, gen_ui.SLOT_Y[r] - my, w, gen_ui.SLOT_H + 2 * my) for r in range(4)]
    if direction == "Row":          # banks from the bottom row (Q-Link 1..4) up
        return rects[::-1]
    if direction == "RowTopDown":
        return rects
    return list(gen_ui.QLINK_BOUNDS)


def build_tree(spec, params, pages, style, frames, shared, dynamics, flags):
    # Every kit asset at its gen_ui name and size; the per-colour files replace them below.
    kit_assets = {name: (name + ".png", n, (w, h)) for name, (w, h, n) in KIT_SIZES.items()}
    phantoms = []
    for name, items in sorted(shared.items()):
        for i, ctl in items:
            controls = [gen_ui.Control("empty")] * 16
            controls[i] = ctl
            phantoms.append((name, gen_ui.Page("~shared~", controls)))
    tui = gen_ui.build_tui(pages + [pg for _, pg in phantoms], params, style, None, frames, kit_assets)
    qlinks = gen_ui.build_qlinks(pages, params)
    tabs = oget(oget(tui, "pageData"), "tabs")
    for (name, _), ptab in zip(phantoms, tabs[len(pages):]):
        # The phantom tab holds only the shared control (and its captions): move them after the
        # occupant's entries on the real tab.
        extra = oget(oget(ptab, "componentDefinition"), "componentsData")
        target = oget(oget(tabs[[pg.name for pg in pages].index(name)], "componentDefinition"), "componentsData")
        slot = oget(oget(extra[0], "bounds"), "bounds")
        at = next(i for i, e in enumerate(target)
                  if oget(oget(e, "bounds"), "bounds") == slot and oget(oget(e, "componentData"), "type") != "Label")
        occupant = oget(oget(target[at], "componentData"), "name")
        while at + 1 < len(target) and oget(oget(target[at + 1], "componentData"), "name").startswith(occupant + " seg "):
            at += 1
        target[at + 1:at + 1] = extra
    del tabs[len(pages):]

    direction = spec["gb"]["qlinks"]["bankDirection"]
    bounds = qlink_rows(direction, spec["gb"]["qlinks"].get("boundsMargin", (8, 6)))
    for tab, page in zip(tabs, pages):
        children = oget(oget(tab, "componentDefinition"), "componentsData")
        image = gen_ui.obj(("version", 2), ("imageType", "Regular"), ("colour", "0"),
                           ("image", background_file(page.name)))
        dyn = [dynamic_entry(d) for d in dynamics.get(page.name, [])
               if (d["kind"] == "filmStrip" and flags["filmStrips"]) or (d["kind"] == "valueLabel" and flags["valueLabels"])]
        children[0:0] = [gen_ui.entry("background", "Image", image, "0 0 %d %d" % (TAB_W, TAB_H),
                                      "No", "Show", "Always")] + dyn
        oset(tab, "qlinkBoundsData", list(bounds))
    for e in oget(oget(qlinks, "Screen Mode Q-Links"), "map"):
        oset(e, "Bank Direction", direction)
    return tui, qlinks


def colour_kit_definitions(tui, pages, colours):
    """Clone each kit component definition per accent colour and point every tab entry at its clone.

    Returns the set of (kit base name, colour or None) the tree now references."""
    page_data = oget(tui, "pageData")
    defs_list = oget(oget(page_data, "componentDefinitions"), "localComponentDefinitions")
    defs = {oget(d, "key"): oget(d, "value") for d in defs_list}

    def kit_images(v):
        return {os.path.splitext(f)[0] for f in gen_ui.referenced_images(v, set())} & set(KIT_SIZES)

    kit_defs = {k for k, v in defs.items() if kit_images(v) & set(COLOURED_KIT)}
    clones = {}   # original name -> [(clone name, value)]
    for tab, page in zip(oget(page_data, "tabs"), pages):
        for e in oget(oget(tab, "componentDefinition"), "componentsData"):
            cd = oget(e, "componentData")
            t = oget(cd, "type")
            if t not in kit_defs:
                continue
            colour = colours.control(page.name, oget(cd, "name"))
            new = "%s_%s" % (t, colour)
            if new not in [n for n, _ in clones.get(t, [])]:
                v = deep_copy(defs[t])
                rewrite_images(v, lambda f, c=colour: kit_file(os.path.splitext(f)[0], c))
                clones.setdefault(t, []).append((new, v))
            oset(cd, "type", new)
    out = []
    for d in defs_list:
        k = oget(d, "key")
        if k in kit_defs:
            out.extend(gen_ui.obj(("key", n), ("value", v)) for n, v in clones.get(k, []))
        else:
            out.append(d)
    defs_list[:] = out
    used = set()
    for img in gen_ui.referenced_images(tui, set()):
        base = os.path.splitext(img)[0]
        if base in KIT_SIZES:
            used.add((base, None))
        else:
            head, _, tail = base.rpartition("_")
            if head in COLOURED_KIT:
                used.add((head, tail))
    return used


