class Art:
    """Every PNG the UI uses, rendered in memory: file -> (frame w, frame h, frames, png bytes, Pix frames)."""

    def __init__(self):
        self.files = {}

    def add(self, name, frames):
        f0 = frames[0]
        rows = ui_art.strip_rows(frames)
        self.files[name + ".png"] = (f0.w, f0.h, len(frames), png_bytes(f0.w, rows), frames)

    def frame(self, file, index):
        return self.files[file][4][index]


def background_file(page_name):
    return "bg_%s.png" % "".join(ch for ch in page_name.lower() if ch.isalnum())


def kit_file(base, colour):
    return "%s_%s.png" % (base, colour) if base in COLOURED_KIT else base + ".png"


def render_kit_asset(P, base, colour):
    accent = P.accent(colour) if colour else None
    if base in ("knob_uni", "knob_bi"):
        return ui_art.render_knob(P, FRAMES, base == "knob_bi", accent)
    if base in ("fader_h_uni", "fader_h_bi"):
        return ui_art.render_fader(P, FRAMES, base == "fader_h_bi", accent)
    if base in ("toggle_on", "toggle_off"):
        return [ui_art.render_toggle(P, base == "toggle_on", accent)]
    n, state = int(base[3]), base.split("_")[1]
    return [ui_art.render_segment(P, gen_ui.SEGMENTS[n][0], state == "on", accent)]


def strip_file(art_kind, colour=None):
    name = STRIP_FILES[art_kind]
    return (name % colour if "%s" in name else name) + ".png"


def render_strip(P, art_kind, colour):
    if art_kind == "duty":
        return ui_art.render_duty_strip(P)
    if art_kind == "waveShape":
        return ui_art.render_wave_strip(P)
    if art_kind == "envTime":
        return ui_art.render_env_strip(P)
    if art_kind == "envDir":
        return ui_art.render_envdir_strip(P)
    return ui_art.render_led_strip(P, P.accent(colour), art_kind == "ledLcd")


def render_art(spec, P, kit_used, strips_used, layout_pages, colours):
    """kit_used: {(base, colour or None)}; strips_used: {(art kind, colour or None)}."""
    gb = spec["gb"]
    art = Art()
    for base, colour in sorted(kit_used, key=lambda t: (t[0], t[1] or "")):
        frames = render_kit_asset(P, base, colour)
        w, h, n = KIT_SIZES[base]
        if (frames[0].w, frames[0].h, len(frames)) != (w, h, n):
            raise BuildError("kit asset %s renders %dx%d x %d, gen_ui expects %dx%d x %d"
                             % (base, frames[0].w, frames[0].h, len(frames), w, h, n))
        art.add(os.path.splitext(kit_file(base, colour))[0], frames)
    for kind, colour in sorted(strips_used, key=lambda t: (t[0], t[1] or "")):
        art.add(os.path.splitext(strip_file(kind, colour))[0], render_strip(P, kind, colour))

    # Editor-only art
    tb = gb["tabBar"]
    n = len(layout_pages)
    first_x = (TAB_W - ((n - 1) * tb["pitch"] + tb["buttonWidth"])) // 2
    lines = [(first_x + i * tb["pitch"] + TAB_UNDERLINE_INSET, TAB_UNDERLINE_Y, tb["buttonWidth"] - 2 * TAB_UNDERLINE_INSET,
              P.accent(colours.page(pg["name"]))) for i, pg in enumerate(layout_pages)]
    art.add("tab_bar", [ui_art.render_tab_bar(P, TAB_W, tb["height"], lines)])
    art.add("tab_on", [ui_art.render_tab_button(P, tb["buttonWidth"], tb["buttonHeight"], True)])
    art.add("tab_off", [ui_art.render_tab_button(P, tb["buttonWidth"], tb["buttonHeight"], False)])
    for name, plist in gb["panels"].items():
        for p in plist:
            if p["kind"] == "lcdTable":
                b = panel_bounds(p)
                img, _ = ui_art.render_lcd_panel(P, b[2], b[3])
                art.add(os.path.splitext(p["image"])[0], [img])
                grid = p["grid"]
                art.add(os.path.splitext(grid["cursorImage"])[0], [ui_art.render_cursor(P, grid["charScale"])])
    return art


def grid_origin(bounds, inset, grid):
    return bounds[0] + inset + grid["padding"], bounds[1] + inset + grid["padding"]


def table_metrics(bounds, inset, grid):
    """(ox, oy, inner_w, line_chars): the text origin, the text area width and how many font cells fit a line.

    Raises BuildError when a column does not fit the line."""
    ox, oy = grid_origin(bounds, inset, grid)
    inner_w = bounds[2] - 2 * inset - 2 * grid["padding"]
    line_chars = inner_w // (ui_art.FONT_ADVANCE * grid["charScale"])
    for col in grid["columns"]:
        if col["x"] + max(col["chars"], len(col["title"])) > line_chars:
            raise BuildError("table column %r (x=%d, %d chars) overflows the %d-character line"
                             % (col["title"], col["x"], max(col["chars"], len(col["title"])), line_chars))
    return ox, oy, inner_w, line_chars


def cursor_band(bounds, grid):
    """The cursor-row band of line 1 (tab coordinates), as the editor's tableCursorBand(1)."""
    ox, oy, inner_w, _ = table_metrics(bounds, ui_art.LCD_INSET, grid)
    adv = ui_art.FONT_ADVANCE * grid["charScale"]
    s = grid["charScale"]
    return (ox + adv - TABLE_BAND_PAD, oy + grid["rowPitch"] - TABLE_BAND_PAD, inner_w - adv + 2 * TABLE_BAND_PAD,
            ui_art.FONT_H * s + 2 * TABLE_BAND_PAD)


def table_column_label_bounds(bounds, grid, column):
    """Bounds of the MPC's live cursor-row Value label under grid column `column`."""
    ox, oy, inner_w, _ = table_metrics(bounds, ui_art.LCD_INSET, grid)
    adv = ui_art.FONT_ADVANCE * grid["charScale"]
    cols = grid["columns"]
    x = ox + cols[column]["x"] * adv
    right = ox + cols[column + 1]["x"] * adv - adv // 2 if column + 1 < len(cols) else ox + inner_w
    band = cursor_band(bounds, grid)
    return (x, band[1], right - x, band[3])


