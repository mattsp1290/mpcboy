# The skin tree
# --------------------------------------------------------------------------------------------
def build_tree(params, pages, style, frames, art):
    kit_assets = {}
    for name in KIT_NAMES:
        w, h, n, _, _ = art.files[name + ".png"]
        kit_assets[name] = (name + ".png", n, (w, h))
    tui = gen_ui.build_tui(pages, params, style, None, frames, kit_assets)
    qlinks = gen_ui.build_qlinks(pages, params)
    for tab, page in zip(oget(oget(tui, "pageData"), "tabs"), pages):
        children = oget(oget(tab, "componentDefinition"), "componentsData")
        image = gen_ui.obj(("version", 2), ("imageType", "Regular"), ("colour", "0"),
                           ("image", background_file(page.name)))
        children.insert(0, gen_ui.entry("background", "Image", image, "0 0 %d %d" % (TAB_W, TAB_H),
                                        "No", "Show", "Always"))
    return tui, qlinks


# --------------------------------------------------------------------------------------------
# Walking the tree into a layout model (shared by ui_layout.inc and the previews)
# --------------------------------------------------------------------------------------------
KIND_ENUM = {"sliderWithFocus": "SliderWithFocus", "knobUni": "KnobUni", "knobBi": "KnobBi",
             "faderUni": "FaderUni", "faderBi": "FaderBi", "toggle": "Toggle",
             "radio2": "Radio2", "radio3": "Radio3", "radio4": "Radio4"}
CHILD_ENUM = {"Focus": "Focus", "Slider": "Slider", "Knob": "Knob", "Label": "Label", "Button": "Button",
              "Image": "Image", "KnobOverlay": "KnobOverlay", "MenuOverlay": "MenuOverlay"}


def walk_layout(tui, params):
    by_index = {p.index: p for p in params}
    page_data = oget(tui, "pageData")
    defs = []
    for d in oget(oget(page_data, "componentDefinitions"), "localComponentDefinitions"):
        name = oget(d, "key")
        children = []
        for e in oget(oget(d, "value"), "componentsData"):
            cd, b = oget(e, "componentData"), oget(e, "bounds")
            t = oget(cd, "type")
            if t not in CHILD_ENUM:
                raise BuildError("component %s: child type %s has no editor mapping" % (name, t))
            data = oget(cd, "data")
            keys = dict(data)  # last-wins view for plain lookups
            ch = {"name": oget(cd, "name"), "type": t, "bounds": parse_rect(oget(b, "bounds")),
                  "focusOnly": oget(b, "whenVisible") == "WhenFocussed",
                  "image": keys.get("filmStrip") or keys.get("onImage") or keys.get("image") or "",
                  "offImage": keys.get("offImage", ""), "frames": int(keys.get("numFrames", 1)),
                  "drag": "None", "buttonId": int(keys.get("buttonId", 0)),
                  "buttons": int(keys.get("numButtonsInGroup", 0)), "label": "None", "colour": 0,
                  "height": 0.0, "justify": "Left"}
            if t == "Knob":
                ch["drag"] = keys.get("dragOrientation", "Vertical")
            if t == "Label":
                ts = keys["textStyle"]
                font = oget(ts, "font")
                j = oget(ts, "justification")
                ch.update(label=keys["type"], colour=int(oget(ts, "colour"), 16), height=float(oget(font, "height")),
                          justify="Centre" if "horizontallyCentred" in j else ("Right" if "right" in j.split() else "Left"))
            children.append(ch)
        defs.append({"name": name, "children": children})
    def_index = {d["name"]: i for i, d in enumerate(defs)}

    pages = []
    for tab in oget(page_data, "tabs"):
        entries = oget(oget(tab, "componentDefinition"), "componentsData")
        first = oget(entries[0], "componentData")
        if oget(first, "type") != "Image":
            raise BuildError("tab %s: first entry is not the background Image" % oget(tab, "tabName"))
        page = {"name": oget(tab, "tabName"), "background": oget(oget(first, "data"), "image"), "controls": []}
        for e in entries[1:]:
            cd, b = oget(e, "componentData"), oget(e, "bounds")
            t = oget(cd, "type")
            bounds = parse_rect(oget(b, "bounds"))
            if t in def_index:
                remap = {oget(m, "key"): oget(m, "value") for m in oget(oget(e, "handle remapping"), "map")}
                index = int(remap["Data"].split()[-1])
                name = oget(cd, "name")
                if by_index[index].name != name:
                    raise BuildError("control %s is bound to Parameter %d (%s)" % (name, index, by_index[index].name))
                menu = t.endswith("Menu")
                base = t[:-4] if menu else t
                vis = (-1, 0, 0)
                inval = dict(b).get("additionalInvalidatingHandles")
                if inval:
                    _, idx, count, handle = inval[0].split("/", 3)
                    vis = (int(handle.split()[-1]), int(idx), int(count))
                page["controls"].append({"param": index, "name": name, "kind": KIND_ENUM[base], "menu": menu,
                                         "component": def_index[t], "slot": bounds, "visible": vis, "captions": []})
            elif t == "Label" and page["controls"] and oget(cd, "name").startswith(page["controls"][-1]["name"] + " seg "):
                data = oget(cd, "data")
                height = float(oget(oget(oget(data, "textStyle"), "font"), "height"))
                page["controls"][-1]["captions"].append((oget(data, "text"), bounds, height))
            else:
                raise BuildError("tab %s: entry %s (%s) has no editor mapping" % (page["name"], oget(cd, "name"), t))
        pages.append(page)
    return defs, pages


# --------------------------------------------------------------------------------------------
# C++ emitters
# --------------------------------------------------------------------------------------------
def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"' if s else "nullptr"


def crect(r):
    return "{%d, %d, %d, %d}" % r


def argb(hex_text):
    h = hex_text.lower()
    return int(h if len(h) == 8 else "ff" + h, 16)


def emit_layout(spec, style, defs, pages, art, P):
    gb = spec["gb"]
    pal = gb["palette"]
    out = ["// %s" % GENERATED_NOTE,
           "// Included by src/ui/ui_layout.h inside namespace mpcboy::ui. All bounds are in design units",
           "// (%d x %d per tab; one design unit = one point in the Mac editor)." % (TAB_W, TAB_H), ""]
    theme = [argb(style[k]) for k in ("background", "accent", "text", "muted")]
    theme += [argb(pal[k]) for k in ("lcdDarkest", "lcdDark", "lcdLight", "lcdLightest", "lcdPanel", "shellLight",
                                     "shellDark", "labelAccent", "magenta", "caption")]
    out.append("inline constexpr Theme kTheme = {%s};" % ", ".join("0x%08xu" % v for v in theme))
    out.append("")
    out.append("inline constexpr Asset kAssets[] = {")
    for f in sorted(art.files):
        w, h, n, _, _ = art.files[f]
        out.append("    {%s, %d, %d, %d}," % (cstr(f), w, h, n))
    out.append("};")
    out.append("inline constexpr int kNumAssets = %d;" % len(art.files))
    out.append("")
    for i, d in enumerate(defs):
        out.append("inline constexpr ChildDef kComponent%dChildren[] = {  // %s" % (i, d["name"]))
        for c in d["children"]:
            out.append("    {%s, ChildType::%s, %s, %s, %s, %s, %d, Drag::%s, %d, %d, LabelKind::%s, 0x%08xu, %.1ff, Justify::%s},"
                       % (cstr(c["name"]), CHILD_ENUM[c["type"]], crect(c["bounds"]), "true" if c["focusOnly"] else "false",
                          cstr(c["image"]), cstr(c["offImage"]), c["frames"], c["drag"], c["buttonId"], c["buttons"],
                          c["label"], c["colour"], c["height"], c["justify"]))
        out.append("};")
    out.append("inline constexpr ComponentDef kComponents[] = {")
    for i, d in enumerate(defs):
        out.append("    {%s, kComponent%dChildren, %d}," % (cstr(d["name"]), i, len(d["children"])))
    out.append("};")
    out.append("inline constexpr int kNumComponents = %d;" % len(defs))
    out.append("")

    for pi, page in enumerate(pages):
        for ci, c in enumerate(page["controls"]):
            if c["captions"]:
                out.append("inline constexpr Caption kPage%dControl%dCaptions[] = {%s};" % (
                    pi, ci, ", ".join("{%s, %s, %.1ff}" % (cstr(t), crect(r), h) for t, r, h in c["captions"])))
        out.append("inline constexpr Control kPage%dControls[] = {  // %s" % (pi, page["name"]))
        for ci, c in enumerate(page["controls"]):
            caps = ("kPage%dControl%dCaptions, %d" % (pi, ci, len(c["captions"]))) if c["captions"] else "nullptr, 0"
            out.append("    {%d, %s, WidgetKind::%s, %s, %d, %s, {%d, %d, %d}, %s},"
                       % (c["param"], cstr(c["name"]), c["kind"], "true" if c["menu"] else "false", c["component"],
                          crect(c["slot"]), c["visible"][0], c["visible"][1], c["visible"][2], caps))
        out.append("};")
        panels = gb["panels"].get(page["name"], [])
        if panels:
            out.append("inline constexpr Panel kPage%dPanels[] = {" % pi)
            for p in panels:
                out.append("    {PanelKind::LcdTable, %s, %s}," % (crect(panel_bounds(p)), cstr(p["image"])))
            out.append("};")
    out.append("inline constexpr Page kPages[] = {")
    for pi, page in enumerate(pages):
        panels = gb["panels"].get(page["name"], [])
        out.append("    {%s, %s, %s, kPage%dControls, %d, %s}," % (
            cstr(page["name"]), cstr(gb["titles"][page["name"]]), cstr(page["background"]), pi, len(page["controls"]),
            ("kPage%dPanels, %d" % (pi, len(panels))) if panels else "nullptr, 0"))
    out.append("};")
    out.append("inline constexpr int kNumPages = %d;" % len(pages))
    out.append("")

    tb = gb["tabBar"]
    n = len(pages)
    first_x = (TAB_W - ((n - 1) * tb["pitch"] + tb["buttonWidth"])) // 2
    y = TAB_H if tb["position"] == "bottom" else 0
    out.append("// Editor tab bar (%s of the window): one button per page." % tb["position"])
    out.append("inline constexpr TabBar kTabBar = {%s, %s, %s, %s, %d, %d, %d};" % (
        crect((0, y, TAB_W, tb["height"])), cstr("tab_bar.png"), cstr("tab_on.png"), cstr("tab_off.png"),
        first_x, (tb["height"] - tb["buttonHeight"]) // 2, tb["pitch"]))
    out.append("inline constexpr Rect kTabButtonSize = {0, 0, %d, %d};" % (tb["buttonWidth"], tb["buttonHeight"]))
    out.append("inline constexpr int kTabWidth = %d;   // one page (tab content)" % TAB_W)
    out.append("inline constexpr int kTabHeight = %d;" % TAB_H)
    out.append("inline constexpr int kEditorWidth = %d;" % TAB_W)
    out.append("inline constexpr int kEditorHeight = %d;" % (TAB_H + tb["height"]))
    out.append("inline constexpr int kContentY = %d;  // tab content origin inside the editor window" % (0 if tb["position"] == "bottom" else tb["height"]))
    out.append("")

    grids = [(pg, p) for pg in pages for p in gb["panels"].get(pg["name"], []) if p["kind"] == "lcdTable"]
    if len(grids) != 1:
        raise BuildError("expected exactly one lcdTable panel, found %d" % len(grids))
    pg, p = grids[0]
    g = p["grid"]
    b = panel_bounds(p)
    inset = ui_art.LCD_INSET
    ox, oy, inner_w, line_chars = table_metrics(b, inset, g)
    out.append("inline constexpr TableColumn kTableColumns[] = {%s};" % ", ".join(
        "{%s, %d, %d}" % (cstr(c["title"]), c["x"], c["chars"]) for c in g["columns"]))
    out.append("inline constexpr int kTableLineChars = %d;   // font cells per text line (the LCD text area)" % line_chars)
    out.append("inline constexpr int kTableInnerWidth = %d;   // text area width, design units" % inner_w)
    out.append("inline constexpr int kTableBandPad = %d;      // highlight bands extend this far around the text cells" % TABLE_BAND_PAD)
    out.append("// Text grid of the TABLE page LCD (tab coordinates): header row, then visibleRows rows.")
    out.append("inline constexpr TableGrid kTableGrid = {%d, %s, %d, %d, %d, %d, %d, %s, %s, kTableColumns, %d};" % (
        [x["name"] for x in pages].index(pg["name"]), crect(b), ox, oy, g["charScale"], g["rowPitch"], g["visibleRows"],
        cstr(p["image"]), cstr(g["cursorImage"]), len(g["columns"])))
    out.append("")
    out.append("// Text sizes (shared by the previews and the editor).")
    out.append("inline constexpr float kLabelScaleThreshold = %.1ff;   // font height below this: 2x font pixels, else 3x" % LABEL_SCALE_THRESHOLD)
    out.append("inline constexpr float kTabTitleFontHeight = %.1ff;" % TAB_TITLE_FONT_H)
    out.append("// Firmware slider approximation: a name row and a value row (each kSliderRowHeight tall), then a")
    out.append("// value bar frame kSliderBarBottom above the bottom edge.")
    out.append("inline constexpr int kSliderRowHeight = %d;" % SLIDER_ROW_H)
    out.append("inline constexpr float kSliderNameFontHeight = %.1ff;" % SLIDER_NAME_FONT_H)
    out.append("inline constexpr float kSliderValueFontHeight = %.1ff;" % SLIDER_VALUE_FONT_H)
    out.append("inline constexpr int kSliderBarBottom = %d;" % SLIDER_BAR_BOTTOM)
    out.append("inline constexpr int kSliderBarHeight = %d;" % SLIDER_BAR_H)
    return "\n".join(out) + "\n"


def emit_font():
    out = ["// %s" % GENERATED_NOTE,
           "// 5 x 7 pixel font shared by the editor and the generated page titles.",
           "// rows[r] bit 4 is the leftmost column; advance %d cells per character." % ui_art.FONT_ADVANCE, "",
           "inline constexpr int kPixelFontWidth = %d;" % ui_art.FONT_W,
           "inline constexpr int kPixelFontHeight = %d;" % ui_art.FONT_H,
           "inline constexpr int kPixelFontAdvance = %d;" % ui_art.FONT_ADVANCE,
           "inline constexpr PixelGlyph kPixelFont[] = {"]
    for ch in sorted(ui_art.GLYPHS):
        lit = "'\\''" if ch == "'" else "'%s'" % ch
        out.append("    {%s, {%s}}," % (lit, ", ".join("0x%02x" % r for r in ui_art.GLYPHS[ch])))
    out.append("};")
    out.append("inline constexpr int kPixelFontCount = %d;" % len(ui_art.GLYPHS))
    return "\n".join(out) + "\n"


