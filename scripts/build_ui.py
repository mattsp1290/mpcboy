def preview_text(img, text, bounds, height, justify, colour):
    x, y, w, h = bounds
    s = label_scale(height)
    tw = ui_art.text_width(text, s)
    tx = x if justify == "Left" else (x + w - tw if justify == "Right" else x + (w - tw) // 2)
    ty = y + (h - ui_art.FONT_H * s) // 2
    ui_art.draw_text(img, text, tx, ty, s, colour, clip=(x, y, x + w, y + h))


def argb_bytes(v):
    return bytes(((v >> 16) & 255, (v >> 8) & 255, v & 255, 255))


def render_preview(page, defs, art, params, style, P):
    by_index = {p.index: p for p in params}
    img = art.frame(page["background"], 0).copy()
    for c in page["controls"]:
        vp, vidx, vcount = c["visible"]
        if vp >= 0:
            d = by_index[vp].default or 0.0
            if int(round(d * (vcount - 1))) != vidx:
                continue  # hidden at the defaults
        p = by_index[c["param"]]
        val = p.default or 0.0
        sx, sy = c["slot"][0], c["slot"][1]
        for ch in defs[c["component"]]["children"]:
            if ch["focusOnly"]:
                continue
            bx, by, bw, bh = ch["bounds"]
            bx, by = bx + sx, by + sy
            if ch["type"] == "Knob":
                n = art.files[ch["image"]][2]
                img.blit(art.frame(ch["image"], int(round(val * (n - 1)))), bx, by)
            elif ch["type"] == "Button":
                steps = max(ch["buttons"], 2)
                lit = int(round(val * (steps - 1))) == ch["buttonId"]
                f = art.frame(ch["image"] if lit else ch["offImage"], 0)
                img.blit(f, bx + (bw - f.w) // 2, by + (bh - f.h) // 2)
            elif ch["type"] == "Label":
                text = p.name if ch["label"] == "Name" else p.display
                preview_text(img, text.upper(), (bx, by, bw, bh), ch["height"], ch["justify"], argb_bytes(ch["colour"]))
            elif ch["type"] == "Slider":
                # Approximation: the firmware draws its own (unthemable) slider with name and value.
                muted, text_c = argb_bytes(int(style["muted"], 16)), argb_bytes(int(style["text"], 16))
                preview_text(img, p.name.upper(), (bx, by, bw, SLIDER_ROW_H), SLIDER_NAME_FONT_H, "Left", muted)
                preview_text(img, p.display.upper(), (bx, by + SLIDER_ROW_H, bw, SLIDER_ROW_H), SLIDER_VALUE_FONT_H, "Left", text_c)
                img.frame(bx, by + bh - SLIDER_BAR_BOTTOM, bw, SLIDER_BAR_H, muted)
                img.rect(bx + 1, by + bh - SLIDER_BAR_BOTTOM + 1, int((bw - 2) * val), SLIDER_BAR_H - 2, text_c)
        for text, (x, y, w, h), height in c["captions"]:
            preview_text(img, text.upper(), (x, y, w, h), height, "Centre", P.caption)
    return img


def render_tabbar_preview(spec, pages, art, P):
    tb = spec["gb"]["tabBar"]
    img = art.frame("tab_bar.png", 0).copy()
    n = len(pages)
    first_x = (TAB_W - ((n - 1) * tb["pitch"] + tb["buttonWidth"])) // 2
    by = (tb["height"] - tb["buttonHeight"]) // 2
    for i, page in enumerate(pages):
        on = i == 1
        btn = art.frame("tab_on.png" if on else "tab_off.png", 0)
        x = first_x + i * tb["pitch"]
        img.blit(btn, x, by)
        title = spec["gb"]["titles"][page.name]
        preview_text(img, title, (x, by, btn.w, btn.h), TAB_TITLE_FONT_H, "Centre", P.caption if on else P.shell)
    return img


