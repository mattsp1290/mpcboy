def load_spec(path):
    try:
        with open(path, "r", encoding="utf-8") as f:
            spec = json.load(f)
    except (OSError, ValueError) as e:
        raise BuildError("cannot read %s: %s" % (path, e))
    if not isinstance(spec, dict) or set(spec) != {"mpc", "gb"}:
        raise BuildError('%s: top level must have exactly the keys "mpc" and "gb"' % path)
    gb = spec["gb"]
    for key in ("palette", "titles", "panels", "tabBar", "wordmark"):
        if key not in gb:
            raise BuildError('%s: "gb" needs "%s"' % (path, key))
    return spec


def panel_bounds(p):
    r, c, nr, nc = p["row"], p["col"], p["rows"], p["cols"]
    if not (0 <= r and 0 <= c and r + nr <= 4 and c + nc <= 4 and nr >= 1 and nc >= 1):
        raise BuildError("panel %r is outside the 4 x 4 slot grid" % p)
    x, y = gen_ui.SLOT_X[c], gen_ui.SLOT_Y[r]
    return (x, y, gen_ui.SLOT_X[c + nc - 1] + gen_ui.SLOT_W - x, gen_ui.SLOT_Y[r + nr - 1] + gen_ui.SLOT_H - y)


# --------------------------------------------------------------------------------------------
# Art
# --------------------------------------------------------------------------------------------
class Art:
    """Every PNG the UI uses, rendered in memory: file -> (frame w, frame h, frames, png bytes, Pix frames)."""

    def __init__(self):
        self.files = {}

    def add(self, name, frames):
        f0 = frames[0]
        rows = ui_art.strip_rows(frames)
        self.files[name + ".png"] = (f0.w, f0.h, len(frames), png_bytes(f0.w, rows), frames)

    def frame(self, file, index):
        return self.files[file][4][index]


def background_file(page_name):
    return "bg_%s.png" % "".join(ch for ch in page_name.lower() if ch.isalnum())


def render_art(spec, pages, P):
    gb = spec["gb"]
    art = Art()
    art.add("knob_uni", ui_art.render_knob(P, FRAMES, False))
    art.add("knob_bi", ui_art.render_knob(P, FRAMES, True))
    art.add("fader_h_uni", ui_art.render_fader(P, FRAMES, False))
    art.add("fader_h_bi", ui_art.render_fader(P, FRAMES, True))
    art.add("toggle_on", [ui_art.render_toggle(P, True)])
    art.add("toggle_off", [ui_art.render_toggle(P, False)])
    for n, (w, _) in sorted(gen_ui.SEGMENTS.items()):
        art.add("seg%d_on" % n, [ui_art.render_segment(P, w, True)])
        art.add("seg%d_off" % n, [ui_art.render_segment(P, w, False)])

    # Editor-only art
    tb = gb["tabBar"]
    art.add("tab_bar", [ui_art.render_tab_bar(P, TAB_W, tb["height"])])
    art.add("tab_on", [ui_art.render_tab_button(P, tb["buttonWidth"], tb["buttonHeight"], True)])
    art.add("tab_off", [ui_art.render_tab_button(P, tb["buttonWidth"], tb["buttonHeight"], False)])

    panel_art = {}
    for page in pages:
        for p in gb["panels"].get(page.name, []):
            if p["kind"] != "lcdTable":
                raise BuildError("unknown panel kind %r" % p["kind"])
            b = panel_bounds(p)
            img, inset = ui_art.render_lcd_panel(P, b[2], b[3])
            art.add(os.path.splitext(p["image"])[0], [img])
            grid = p["grid"]
            art.add(os.path.splitext(grid["cursorImage"])[0], [ui_art.render_cursor(P, grid["charScale"])])
            panel_art[(page.name, id(p))] = inset

    # Page backgrounds: dark field, LCD panel, title, wordmark, plus decorative panels
    for page in pages:
        title = gb["titles"].get(page.name)
        if not title:
            raise BuildError('"gb.titles" has no title for page "%s"' % page.name)
        bg = ui_art.render_background(P, title, gb["wordmark"])
        for p in gb["panels"].get(page.name, []):
            b = panel_bounds(p)
            panel = art.frame(p["image"], 0)
            bg.blit(panel, b[0], b[1])
            decorate_table(bg, P, b, panel_art[(page.name, id(p))], p["grid"], art.frame(p["grid"]["cursorImage"], 0))
        art.add(os.path.splitext(background_file(page.name))[0], [bg])
    return art


def grid_origin(bounds, inset, grid):
    return bounds[0] + inset + grid["padding"], bounds[1] + inset + grid["padding"]


def table_metrics(bounds, inset, grid):
    """(ox, oy, inner_w, line_chars): the text origin, the text area width and how many font cells fit a line.

    Raises BuildError when a column does not fit the line."""
    ox, oy = grid_origin(bounds, inset, grid)
    inner_w = bounds[2] - 2 * inset - 2 * grid["padding"]
    line_chars = inner_w // (ui_art.FONT_ADVANCE * grid["charScale"])
    for col in grid["columns"]:
        if col["x"] + max(col["chars"], len(col["title"])) > line_chars:
            raise BuildError("table column %r (x=%d, %d chars) overflows the %d-character line"
                             % (col["title"], col["x"], max(col["chars"], len(col["title"])), line_chars))
    return ox, oy, inner_w, line_chars


def decorate_table(bg, P, bounds, inset, grid, cursor):
    """The MPC's static stand-in for the editor's live table grid: header, 8 rows, row 0 under the cursor."""
    s = grid["charScale"]
    adv = ui_art.FONT_ADVANCE * s
    ox, oy, inner_w, _ = table_metrics(bounds, inset, grid)
    pad = TABLE_BAND_PAD
    bg.rect(ox - pad, oy - pad, inner_w + 2 * pad, ui_art.FONT_H * s + 2 * pad, P.light)
    for col in grid["columns"]:
        ui_art.draw_text(bg, col["title"], ox + col["x"] * adv, oy, s, P.darkest)
    samples = ("--", "--", "+00", "-", "00", "-", "00")
    for r in range(grid["visibleRows"]):
        y = oy + (r + 1) * grid["rowPitch"]
        ink = P.darkest
        if r == 0:
            bg.rect(ox + adv - pad, y - pad, inner_w - adv + 2 * pad, ui_art.FONT_H * s + 2 * pad, P.darkest)
            ink = P.lightest
            bg.blit(cursor, ox, y)
        for col, text in zip(grid["columns"], ("%02X" % r,) + samples[1:]):
            ui_art.draw_text(bg, text, ox + col["x"] * adv, y, s, ink)


