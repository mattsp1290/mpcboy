#!/usr/bin/env python3
"""build_ui.py - build the shared mpcboy Game Boy UI from ui/mpcboy_ui.json.

One source of truth for both builds:

  * the MPC skin (Plugin Skins/TUI.json, Q-Links.json and the PNGs it references),
    built with the vendored SDK's tools/gen_ui.py as a module;
  * the Mac editor's layout table (src/ui/generated/ui_layout.inc), walked from the
    same in-memory component tree that becomes TUI.json, and the 5 x 7 pixel font
    (src/ui/generated/pixel_font.inc);
  * all art (ui/art/*.png), including editor-only art (tab bar, LCD table panel, cursor);
  * review previews (build/ui-preview/<page>.png): background, kit frames at each
    parameter's default and approximate label text in the pixel font.

Post-processes applied to gen_ui's in-memory Obj tree (never a json round-trip, so the
overlays keep their duplicate "version" keys, ui-reference 1.8):

  * a background Image as the first entry of every tab;
  * shared slots ("gb.sharedSlots"): a control laid over another control's slot with a
    complementary visibleWhen (built by gen_ui on a phantom page, then moved into the tab);
  * MPC dynamics ("gb.dynamics", gated by "gb.mpcDynamics"): parameter-bound Image film
    strips (ui-reference 6.6) and Value labels (6.3), remapped Data -> Parameter N (4.5);
  * per-page kit variants: every kit component definition is cloned per accent colour
    ("knobUni_pu1" uses knob_uni_pu1.png); gen_ui shares one definition across pages;
  * Q-Links "Bank Direction" ("gb.qlinks") and qlinkBoundsData that wrap one screen row.

Usage:
    python3 scripts/build_ui.py [--params build/params.json] [--skins "<dir>/Plugin Skins"]
                                [--root <dir>] [--preview-dir <dir> | --no-preview] [--quiet]

--root redirects ui/art and src/ui/generated (default: the repository), so a
packaging run or a test can generate without touching the tree. Output is
byte-reproducible: running twice gives identical files.

Like gen_ui.py it prints "WARNING"/"NOTE" lines for things a reviewer should look
at; scripts/package_mpc.py fails on any of them.

Standard library only; Python 3.9+.
"""

