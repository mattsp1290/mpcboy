def render_page_background(spec, P, page, colours, dyn_specs, flags, art, qmap):
    """page: a walk_layout page. dyn_specs: the page's resolved dynamics (emitted or not)."""
    gb = spec["gb"]
    name = page["name"]
    accent = P.accent(colours.page(name))
    band = [(l["text"], gen_ui.SLOT_X[l.get("col", 0)]) for l in gb["legends"].get(name, []) if l["row"] == 0]
    bg = ui_art.render_background(P, gb["titles"][name], gb["wordmark"], accent, band)

    covered = set()
    for p in gb["panels"].get(name, []):
        covered.update(slot_cells(p))
    decal_cells = {}
    for d in gb["decals"].get(name, []):
        for cell in slot_cells(d):
            decal_cells[cell] = d
    by_slot = {}
    for c in page["controls"]:
        by_slot.setdefault(c["slot"], []).append(c)

    drawn_decals = set()
    for r in range(4):
        for col in range(4):
            if (r, col) in covered:
                continue
            sx, sy = gen_ui.SLOT_X[col], gen_ui.SLOT_Y[r]
            ctls = by_slot.get((sx, sy, gen_ui.SLOT_W, gen_ui.SLOT_H), [])
            if ctls:
                stripe = None
                if any(colours.explicit(name, c["name"]) for c in ctls):
                    stripe = P.accent(ctls[0]["colour"])
                ui_art.draw_plate(bg, P, sx - 1, sy - 1, gen_ui.SLOT_W + 2, gen_ui.SLOT_H + 1, stripe)
                if len(ctls) == 1 and ctls[0]["kind"] == "SliderWithFocus" and ctls[0]["menu"]:
                    cx, cy, cw, ch = CARTRIDGE
                    ui_art.draw_cartridge(bg, P, sx + cx, sy + cy, cw, ch, P.accent(ctls[0]["colour"]))
                q = gen_ui.slot_qlink(r, col)
                if qmap.get(q, -1) >= 0:
                    ui_art.draw_badge(bg, P, "Q%d" % q, sx + gen_ui.SLOT_W - BADGE_INSET[0], sy + gen_ui.SLOT_H - BADGE_INSET[1])
            elif (r, col) in decal_cells:
                d = decal_cells[(r, col)]
                if id(d) not in drawn_decals:
                    drawn_decals.add(id(d))
                    x, y, w, h = span_bounds(d["row"], d["col"], 1, d.get("cols", 1), "decal")
                    ui_art.draw_recess(bg, P, x - 1, y - 1, w + 2, h + 1, d["text"])
            else:
                ui_art.draw_recess(bg, P, sx - 1, sy - 1, gen_ui.SLOT_W + 2, gen_ui.SLOT_H + 1)

    for l in gb["legends"].get(name, []):
        if l["row"] == 0:
            continue
        ui_art.draw_legend(bg, P, l["text"], gen_ui.SLOT_X[l.get("col", 0)], gen_ui.SLOT_Y[l["row"]] - 26,
                           gen_ui.SLOT_X[3] + gen_ui.SLOT_W, accent)

    for p in gb["panels"].get(name, []):
        b = panel_bounds(p)
        if p["kind"] == "lcdChannel":
            fallbacks = []
            if not flags["filmStrips"]:
                for d in dyn_specs:
                    if d["kind"] == "filmStrip":
                        fallbacks.append((art.frame(d["image"], d["defaultFrame"]), d["bounds"][0], d["bounds"][1]))
            ui_art.draw_channel_lcd(bg, P, b, p["tag"], p["motif"], fallbacks)
        elif p["kind"] == "lcdTable":
            bg.blit(art.frame(p["image"], 0), b[0], b[1])
            decorate_table(bg, P, b, p["grid"], art.frame(p["grid"]["cursorImage"], 0), flags["valueLabels"])
        else:
            raise BuildError("unknown panel kind %r" % p["kind"])
    # Static captions of the dynamics (printed above them, in LCD ink)
    for d in dyn_specs:
        if d.get("caption") and (d["kind"] == "filmStrip" or flags["valueLabels"]):
            ui_art.draw_lcd_caption(bg, P, d["caption"], d["bounds"][0], d["bounds"][1] - 20 if d["kind"] == "filmStrip" else d["bounds"][1] - 18)
    # MAIN's header LEDs etc. outside the LCDs: fallback to the default frame when strips are off
    if not flags["filmStrips"]:
        for d in dyn_specs:
            if d["kind"] == "filmStrip" and d["art"] == "ledPlate":
                bg.blit(art.frame(d["image"], d["defaultFrame"]), d["bounds"][0], d["bounds"][1])
    return bg


def decorate_table(bg, P, bounds, grid, cursor, live_row):
    """The MPC's TABLE LCD: the column header, the live cursor row band (filled by Value labels on
    the MPC) and a printed command reference card. No fake rows."""
    s = grid["charScale"]
    adv = ui_art.FONT_ADVANCE * s
    ox, oy, inner_w, _ = table_metrics(bounds, ui_art.LCD_INSET, grid)
    pad = TABLE_BAND_PAD
    bg.rect(ox - pad, oy - pad, inner_w + 2 * pad, ui_art.FONT_H * s + 2 * pad, P.lcd_beat)
    for col in grid["columns"]:
        ui_art.draw_text(bg, col["title"], ox + col["x"] * adv, oy, s, P.lcd_ink)
    card_y = oy + grid["rowPitch"]
    if live_row:
        x, y, w, h = cursor_band(bounds, grid)
        bg.rect(x, y, w, h, P.lcd_cursor)
        bg.blit(cursor, ox, oy + grid["rowPitch"])
        card_y = oy + 2 * grid["rowPitch"]
    ui_art.draw_command_card(bg, P, ox, card_y + 14, inner_w, grid["commandCard"])


