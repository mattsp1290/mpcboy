def sync_dir(directory, files, keep_ext):
    """Write files {name: bytes} into directory and delete other *keep_ext files there. Returns changed names."""
    os.makedirs(directory, exist_ok=True)
    changed = [n for n, data in sorted(files.items()) if write_if_changed(os.path.join(directory, n), data)]
    for n in sorted(os.listdir(directory)):
        if n.endswith(keep_ext) and n not in files:
            os.remove(os.path.join(directory, n))
            changed.append(n + " (removed)")
    return changed


def check_slots(spec, pages):
    """Panels and decals sit only on empty slots; every gb page name exists."""
    gb = spec["gb"]
    names = [pg.name for pg in pages]
    for key in ("titles", "pageColours"):
        for pg in names:
            if pg not in gb[key]:
                raise BuildError('"gb.%s" has no entry for page "%s"' % (key, pg))
    for key in ("panels", "decals", "legends"):
        for name, items in gb[key].items():
            page = next((pg for pg in pages if pg.name == name), None)
            if page is None:
                raise BuildError('"gb.%s" names page "%s", which is not in "mpc.pages"' % (key, name))
            if key == "legends":
                continue
            for p in items:
                cells = slot_cells(p) if key == "panels" else [(p["row"], c) for c in range(p["col"], p["col"] + p.get("cols", 1))]
                for r, c in cells:
                    i = r * 4 + c
                    if i < len(page.controls) and page.controls[i].widget != "empty":
                        raise BuildError('page "%s": %s covers slot row %d col %d, which holds a control'
                                         % (name, key[:-1], r, c))


def build(args):
    spec = load_spec(args.ui)
    with tempfile.TemporaryDirectory() as tmp:
        mpc_path = os.path.join(tmp, "mpcboy_ui.json (mpc)")
        with open(mpc_path, "w", encoding="utf-8") as f:
            json.dump(spec["mpc"], f)
        params = gen_ui.load_params(args.params)
        table = gen_ui.ParamTable(params)
        pages, style, knob_image, frames, kit = gen_ui.load_ui(mpc_path, table)
    # load_ui fills in a default kit whenever knobs/faders/switches are used; build_ui.py renders its own.
    if "kit" in spec["mpc"] or "knobImage" in spec["mpc"] or "knobFrames" in spec["mpc"]:
        raise BuildError('"mpc" must not set "kit", "knobImage" or "knobFrames": build_ui.py supplies the Game Boy kit')
    if len(pages) > 6:
        print("build_ui: NOTE: %d pages; the MPC screen has six function keys, so tabs beyond the sixth are untested." % len(pages))
    bip = [c.param.name for pg in pages for c in pg.controls if c.widget in ("knob", "fader") and c.polarity == "auto" and c.bipolar]
    if bip:
        print('build_ui: NOTE: drawn bipolar (centre-zero) by auto-detection: %s. Set "polarity" to override.'
              % ", ".join('"%s"' % n for n in bip))
    check_slots(spec, pages)
    gb = spec["gb"]
    flags = gb["mpcDynamics"]
    colours = Colours(gb, pages)
    shared = parse_shared_slots(spec, pages, table)
    dynamics = resolve_dynamics(spec, pages, table)

    install_gen_ui_patches("ff" + gb["palette"]["text"].lower())
    P = ui_art.Palette(gb["palette"], gb["colours"])
    tui, qlinks = build_tree(spec, params, pages, style, frames, shared, dynamics, flags)
    kit_used = colour_kit_definitions(tui, pages, colours)
    qmaps = {}
    for page, e in zip(pages, oget(oget(qlinks, "Screen Mode Q-Links"), "map")):
        qmaps[page.name] = {int(k.split()[-1]): v for k, v in oget(e, "Q-Links")}
    table_panels = {name: panel_bounds(p) for name, plist in gb["panels"].items() for p in plist if p["kind"] == "lcdTable"}
    defs, layout_pages = walk_layout(tui, params, colours, qmaps, table_panels)

    strips_used = {(d["art"], d.get("colour")) for items in dynamics.values() for d in items if d["kind"] == "filmStrip"}
    art = render_art(spec, P, kit_used, strips_used, layout_pages, colours)
    for page in layout_pages:
        bg = render_page_background(spec, P, page, colours, dynamics.get(page["name"], []), flags, art, qmaps[page["name"]])
        art.add(os.path.splitext(background_file(page["name"]))[0], [bg])

    # Render and validate everything in memory first; nothing is written until it all succeeded,
    # so a BuildError never leaves a partial tree.
    art_files = {f: v[3] for f, v in art.files.items()}
    gen_files = {"ui_layout.inc": emit_layout(spec, style, defs, layout_pages, art, colours).encode(),
                 "pixel_font.inc": emit_font().encode()}
    skin_files = {}
    referenced = sorted(gen_ui.referenced_images(tui, set()))
    for img in referenced:
        if img not in art.files:
            raise BuildError("TUI.json references %s, which build_ui.py did not render" % img)
    if args.skins:
        skin_files["TUI.json"] = (gen_ui.dump_json(tui) + "\n").encode("utf-8")
        skin_files["Q-Links.json"] = (gen_ui.dump_json(qlinks) + "\n").encode("utf-8")
        for img in referenced:
            skin_files[img] = art_files[img]
    preview_files = {}
    if args.preview_dir:
        for page in layout_pages:
            preview_files[page["name"].lower() + ".png"] = png_bytes(
                TAB_W, render_preview(page, defs, art, params, style, P, gb).rows())
        preview_files["tabbar.png"] = png_bytes(TAB_W, render_tabbar_preview(spec, pages, art, P).rows())

    root = os.path.abspath(args.root)
    art_dir = os.path.join(root, "ui", "art")
    gen_dir = os.path.join(root, "src", "ui", "generated")
    changed = sync_dir(art_dir, art_files, ".png")
    changed += sync_dir(gen_dir, gen_files, ".inc")
    if not args.quiet:
        print("build_ui: %d art files in %s, layout in %s (%d changed)"
              % (len(art.files), os.path.relpath(art_dir, os.getcwd()), os.path.relpath(gen_dir, os.getcwd()), len(changed)))
        for c in changed:
            print("build_ui:   updated %s" % c)

    if args.skins:
        os.makedirs(args.skins, exist_ok=True)
        for name, data in skin_files.items():
            write_if_changed(os.path.join(args.skins, name), data)
        if not args.quiet:
            n_controls = sum(1 for pg in pages for c in pg.controls if c.param is not None) + sum(len(v) for v in shared.values())
            print("build_ui: wrote %s (TUI.json, Q-Links.json, %d images; %d pages, %d bound controls)"
                  % (args.skins, len(skin_files) - 2, len(pages), n_controls))

    if args.preview_dir:
        sync_dir(args.preview_dir, preview_files, ".png")
        if not args.quiet:
            print("build_ui: previews in %s" % args.preview_dir)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Build the mpcboy Game Boy UI (MPC skin, editor layout, art, previews).")
    ap.add_argument("--params", default=os.path.join(ROOT, "build", "params.json"), help="host_sim dump output")
    ap.add_argument("--ui", default=os.path.join(ROOT, "ui", "mpcboy_ui.json"), help="layout source")
    ap.add_argument("--root", default=ROOT, help="where ui/art and src/ui/generated are written (default: the repo)")
    ap.add_argument("--skins", help='also write the MPC skin here (normally "<plugin folder>/Plugin Skins")')
    ap.add_argument("--preview-dir", default=os.path.join(ROOT, "build", "ui-preview"), help="preview PNG folder")
    ap.add_argument("--no-preview", dest="preview_dir", action="store_const", const=None, help="skip the previews")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)
    try:
        build(args)
    except gen_ui.UiError as e:
        print("build_ui: " + str(e), file=sys.stderr)
        return 1
    except BuildError as e:
        print("build_ui: ERROR: " + str(e), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
