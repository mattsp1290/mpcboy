KIND_ENUM = {"sliderWithFocus": "SliderWithFocus", "knobUni": "KnobUni", "knobBi": "KnobBi",
             "faderUni": "FaderUni", "faderBi": "FaderBi", "toggle": "Toggle",
             "radio2": "Radio2", "radio3": "Radio3", "radio4": "Radio4"}
CHILD_ENUM = {"Focus": "Focus", "Slider": "Slider", "Knob": "Knob", "Label": "Label", "Button": "Button",
              "Image": "Image", "KnobOverlay": "KnobOverlay", "MenuOverlay": "MenuOverlay"}


def label_style(data):
    ts = oget(data, "textStyle")
    font = oget(ts, "font")
    j = oget(ts, "justification")
    return (int(oget(ts, "colour"), 16), float(oget(font, "height")),
            "Centre" if "horizontallyCentred" in j else ("Right" if "right" in j.split() else "Left"))


def walk_layout(tui, params, colours, qmaps, table_panels):
    by_index = {p.index: p for p in params}
    page_data = oget(tui, "pageData")
    defs = []
    for d in oget(oget(page_data, "componentDefinitions"), "localComponentDefinitions"):
        name = oget(d, "key")
        children = []
        for e in oget(oget(d, "value"), "componentsData"):
            cd, b = oget(e, "componentData"), oget(e, "bounds")
            t = oget(cd, "type")
            if t not in CHILD_ENUM:
                raise BuildError("component %s: child type %s has no editor mapping" % (name, t))
            data = oget(cd, "data")
            keys = dict(data)  # last-wins view for plain lookups
            ch = {"name": oget(cd, "name"), "type": t, "bounds": parse_rect(oget(b, "bounds")),
                  "focusOnly": oget(b, "whenVisible") == "WhenFocussed",
                  "image": keys.get("filmStrip") or keys.get("onImage") or keys.get("image") or "",
                  "offImage": keys.get("offImage", ""), "frames": int(keys.get("numFrames", 1)),
                  "drag": "None", "buttonId": int(keys.get("buttonId", 0)),
                  "buttons": int(keys.get("numButtonsInGroup", 0)), "label": "None", "colour": 0,
                  "height": 0.0, "justify": "Left"}
            if t == "Knob":
                ch["drag"] = keys.get("dragOrientation", "Vertical")
            if t == "Label":
                colour, height, justify = label_style(data)
                ch.update(label=keys["type"], colour=colour, height=height, justify=justify)
            children.append(ch)
        defs.append({"name": name, "children": children})
    def_index = {d["name"]: i for i, d in enumerate(defs)}

    pages = []
    for tab in oget(page_data, "tabs"):
        entries = oget(oget(tab, "componentDefinition"), "componentsData")
        first = oget(entries[0], "componentData")
        if oget(first, "type") != "Image":
            raise BuildError("tab %s: first entry is not the background Image" % oget(tab, "tabName"))
        name = oget(tab, "tabName")
        page = {"name": name, "background": oget(oget(first, "data"), "image"), "controls": [], "dynamics": []}
        qmap = qmaps[name]
        panel = table_panels.get(name)
        for e in entries[1:]:
            cd, b = oget(e, "componentData"), oget(e, "bounds")
            t = oget(cd, "type")
            bounds = parse_rect(oget(b, "bounds"))
            remap = {oget(m, "key"): oget(m, "value") for m in oget(oget(e, "handle remapping"), "map")}
            cname = oget(cd, "name")
            if t in def_index:
                index = int(remap["Data"].split()[-1])
                if by_index[index].name != cname:
                    raise BuildError("control %s is bound to Parameter %d (%s)" % (cname, index, by_index[index].name))
                base = t.split("_")[0]
                menu = base.endswith("Menu")
                base = base[:-4] if menu else base
                vis = (-1, 0, 0)
                inval = dict(b).get("additionalInvalidatingHandles")
                if inval:
                    _, idx, count, handle = inval[0].split("/", 3)
                    vis = (int(handle.split()[-1]), int(idx), int(count))
                row, col = gen_ui.SLOT_Y.index(bounds[1]), gen_ui.SLOT_X.index(bounds[0])
                q = gen_ui.slot_qlink(row, col)
                page["controls"].append({"param": index, "name": cname, "kind": KIND_ENUM[base], "menu": menu,
                                         "component": def_index[t], "slot": bounds, "visible": vis, "captions": [],
                                         "colour": colours.control(name, cname),
                                         "qlink": q if qmap.get(q, -1) == index else 0})
            elif t == "Label" and page["controls"] and cname.startswith(page["controls"][-1]["name"] + " seg "):
                data = oget(cd, "data")
                height = float(oget(oget(oget(data, "textStyle"), "font"), "height"))
                page["controls"][-1]["captions"].append((oget(data, "text"), bounds, height))
            elif cname.startswith("dyn ") and t in ("Image", "Label"):
                index = int(remap["Data"].split()[-1])
                data = oget(cd, "data")
                inside = panel is not None and (panel[0] <= bounds[0] and panel[1] <= bounds[1]
                                                and bounds[0] + bounds[2] <= panel[0] + panel[2]
                                                and bounds[1] + bounds[3] <= panel[1] + panel[3])
                dyn = {"param": index, "name": by_index[index].name, "bounds": bounds, "editor": not inside}
                if t == "Image":
                    if oget(data, "imageType") != "FilmStrip":
                        raise BuildError("tab %s: dynamic image %s is not a film strip" % (name, cname))
                    dyn.update(kind="FilmStrip", image=oget(data, "image"), frames=oget(data, "numFrames"),
                               colour=0, height=0.0, justify="Left")
                else:
                    colour, height, justify = label_style(data)
                    dyn.update(kind="ValueLabel", image="", frames=1, colour=colour, height=height, justify=justify)
                page["dynamics"].append(dyn)
            else:
                raise BuildError("tab %s: entry %s (%s) has no editor mapping" % (name, cname, t))
        pages.append(page)
    return defs, pages


