# Obj tree helpers (gen_ui.Obj is an ordered list of (key, value) pairs; keys may repeat)
# --------------------------------------------------------------------------------------------
def oget(o, key):
    for k, v in o:
        if k == key:
            return v
    raise KeyError(key)


def oset(o, key, value):
    for i, (k, _) in enumerate(o):
        if k == key:
            o[i] = (k, value)
            return
    raise KeyError(key)


def deep_copy(v):
    """Copy an Obj tree, keeping Obj (duplicate keys and order) intact."""
    if isinstance(v, gen_ui.Obj):
        return gen_ui.Obj((k, deep_copy(x)) for k, x in v)
    if isinstance(v, list):
        return [deep_copy(x) for x in v]
    return v


def rewrite_images(v, fn):
    """Apply fn to every image file name (filmStrip / onImage / offImage / image) in place."""
    if isinstance(v, gen_ui.Obj):
        for i, (k, x) in enumerate(v):
            if k in IMAGE_KEYS and isinstance(x, str) and x:
                v[i] = (k, fn(x))
            else:
                rewrite_images(x, fn)
    elif isinstance(v, list):
        for x in v:
            rewrite_images(x, fn)


def parse_rect(text):
    x, y, w, h = (int(round(float(v))) for v in text.split())
    return (x, y, w, h)


def rect_str(r):
    return "%d %d %d %d" % r


