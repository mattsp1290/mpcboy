GENERATED_NOTE = "generated by scripts/build_ui.py from ui/mpcboy_ui.json - do not edit"

FONT_NAME = "Nexa"
FONT_STYLE = "Bold"
FONT_CASE = "Upper Case"
# Nexa Bold upper case is wider than gen_ui's Titillium Web Regular; label boxes are fixed,
# so every label height is scaled down a little to keep names like "P1 SWPSHIFT" inside them.
LABEL_HEIGHT_SCALE = 0.85

KIT_NAMES = ("knob_uni", "knob_bi", "fader_h_uni", "fader_h_bi", "toggle_on", "toggle_off",
             "seg2_on", "seg2_off", "seg3_on", "seg3_off", "seg4_on", "seg4_off")
FRAMES = 127
TAB_W, TAB_H = 1280, 628

# Text sizes and table geometry shared with the Mac editor (emitted into ui_layout.inc; the
# editor and the previews both read them from here, nothing is retyped in C++).
LABEL_SCALE_THRESHOLD = 24.0   # a label whose font height is below this uses 2x font pixels, else 3x
TAB_TITLE_FONT_H = 20.0        # tab bar button titles
SLIDER_ROW_H = 30              # firmware slider approximation: name row, then value row, each this tall
SLIDER_NAME_FONT_H = 20.0
SLIDER_VALUE_FONT_H = 26.0
SLIDER_BAR_BOTTOM = 10         # value bar frame: this many units above the slider's bottom edge
SLIDER_BAR_H = 8               # frame height (the fill is 1 unit inside it)
TABLE_BAND_PAD = 2             # highlight bands extend this far around the text cells


def label_scale(font_height):
    return 2 if font_height < LABEL_SCALE_THRESHOLD else 3


class BuildError(Exception):
    pass


# --------------------------------------------------------------------------------------------
# Obj tree helpers (gen_ui.Obj is an ordered list of (key, value) pairs; keys may repeat)
# --------------------------------------------------------------------------------------------
def oget(o, key):
    for k, v in o:
        if k == key:
            return v
    raise KeyError(key)


def oset(o, key, value):
    for i, (k, _) in enumerate(o):
        if k == key:
            o[i] = (k, value)
            return
    raise KeyError(key)


def parse_rect(text):
    x, y, w, h = (int(round(float(v))) for v in text.split())
    return (x, y, w, h)


# --------------------------------------------------------------------------------------------
# gen_ui patches: Nexa Bold, upper case; segment captions in the caption colour
# --------------------------------------------------------------------------------------------
_ORIG_LABEL_DATA = gen_ui.label_data


def install_gen_ui_patches(caption_argb):
    gen_ui.FONT_NAME = FONT_NAME

    def label_data(label_type, colour, height=30.0, justification="left", text=None):
        if label_type == "Text":
            colour = caption_argb  # gen_ui's "Text" labels here are segment captions
        d = _ORIG_LABEL_DATA(label_type, colour, round(height * LABEL_HEIGHT_SCALE, 1), justification, text)
        style = oget(d, "textStyle")
        oset(oget(style, "font"), "style", FONT_STYLE)
        oset(style, "case", FONT_CASE)
        return d

    gen_ui.label_data = label_data


# --------------------------------------------------------------------------------------------
# PNG (same encoding as make_ui_kit.write_png, returned as bytes)
# --------------------------------------------------------------------------------------------
def png_bytes(width, rows):
    def chunk(tag, data):
        body = tag + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)
    raw = b"".join(b"\0" + r for r in rows)
    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", width, len(rows), 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9))
            + chunk(b"IEND", b""))


def write_if_changed(path, data):
    if isinstance(data, str):
        data = data.encode("utf-8")
    try:
        with open(path, "rb") as f:
            if f.read() == data:
                return False
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)
    return True


