GB_KEYS = ("palette", "colours", "pageColours", "controlColours", "wordmark", "titles", "qlinks", "sharedSlots",
           "legends", "decals", "panels", "mpcDynamics", "dynamics", "tabBar")
GB_REQUIRED = ("palette", "colours", "pageColours", "wordmark", "titles", "qlinks", "panels", "mpcDynamics", "tabBar")


def load_spec(path):
    try:
        with open(path, "r", encoding="utf-8") as f:
            spec = json.load(f)
    except (OSError, ValueError) as e:
        raise BuildError("cannot read %s: %s" % (path, e))
    if not isinstance(spec, dict) or set(spec) != {"mpc", "gb"}:
        raise BuildError('%s: top level must have exactly the keys "mpc" and "gb"' % path)
    gb = spec["gb"]
    for key in GB_REQUIRED:
        if key not in gb:
            raise BuildError('%s: "gb" needs "%s"' % (path, key))
    for key in gb:
        if key not in GB_KEYS:
            raise BuildError('%s: unknown "gb" key "%s" (allowed: %s)' % (path, key, ", ".join(GB_KEYS)))
    for key in ("controlColours", "sharedSlots", "legends", "decals", "dynamics"):
        gb.setdefault(key, {})
    flags = gb["mpcDynamics"]
    if set(flags) != {"valueLabels", "filmStrips"} or not all(isinstance(v, bool) for v in flags.values()):
        raise BuildError('"gb.mpcDynamics" must be {"valueLabels": true|false, "filmStrips": true|false}')
    q = gb["qlinks"]
    if q.get("bankDirection") not in BANK_DIRECTIONS:
        raise BuildError('"gb.qlinks.bankDirection" must be one of %s' % ", ".join(BANK_DIRECTIONS))
    return spec


def span_bounds(row, col, rows, cols, where="panel"):
    if not (0 <= row and 0 <= col and row + rows <= 4 and col + cols <= 4 and rows >= 1 and cols >= 1):
        raise BuildError("%s at row %d col %d (%d x %d) is outside the 4 x 4 slot grid" % (where, row, col, rows, cols))
    x, y = gen_ui.SLOT_X[col], gen_ui.SLOT_Y[row]
    return (x, y, gen_ui.SLOT_X[col + cols - 1] + gen_ui.SLOT_W - x, gen_ui.SLOT_Y[row + rows - 1] + gen_ui.SLOT_H - y)


def panel_bounds(p):
    return span_bounds(p["row"], p["col"], p["rows"], p["cols"])


def slot_cells(p):
    return [(r, c) for r in range(p["row"], p["row"] + p.get("rows", 1)) for c in range(p["col"], p["col"] + p.get("cols", 1))]


# --------------------------------------------------------------------------------------------
# Colours: one accent per page, optionally per control ("gb.controlColours")
# --------------------------------------------------------------------------------------------
class Colours:
    def __init__(self, gb, pages):
        self.gb = gb
        for page in pages:
            key = gb["pageColours"].get(page.name)
            if key not in gb["colours"]:
                raise BuildError('"gb.pageColours" needs a colour from "gb.colours" for page "%s"' % page.name)
        for name, m in gb["controlColours"].items():
            page = next((pg for pg in pages if pg.name == name), None)
            if page is None:
                raise BuildError('"gb.controlColours" names page "%s", which is not in "mpc.pages"' % name)
            names = {c.param.name for c in page.controls if c.param is not None}
            for param, key in m.items():
                if param not in names:
                    raise BuildError('"gb.controlColours.%s": no control for "%s" on that page' % (name, param))
                if key not in gb["colours"]:
                    raise BuildError('"gb.controlColours.%s.%s": unknown colour "%s"' % (name, param, key))

    def page(self, page_name):
        return self.gb["pageColours"][page_name]

    def control(self, page_name, param_name):
        return self.gb["controlColours"].get(page_name, {}).get(param_name, self.page(page_name))

    def explicit(self, page_name, param_name):
        return param_name in self.gb["controlColours"].get(page_name, {})


